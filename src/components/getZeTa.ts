const LUNAR_MONTH_OFFSET = 5;

function getMonthIndex(lunarMonth: number) {
  const month = Math.abs(lunarMonth) - 1;
  return (month + LUNAR_MONTH_OFFSET) % 12;
}

function getZodiacIndex(zodiacCn: string) {
  return ZODIAC_CN.findIndex((item) => item === zodiacCn);
}

export function getZeTa(date: string) {
  const lunar = Lunar.fromDate(new Date(date));
  const monthIndex = getMonthIndex(lunar.getMonth());
  const dayZodiac = lunar.getDayShengXiao();
  const zodiacIndex = getZodiacIndex(dayZodiac);
  const monthRow = ZENG_TA[monthIndex];
  if (!monthRow) return undefined;
  return monthRow[zodiacIndex];
}
